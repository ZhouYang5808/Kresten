#!/usr/bin/env python3
"""Generate kernel_symtab.c from a first-pass kernel ELF (two-pass link).

Usage: gen_kernel_symtab.py <kernel.elf.1st> <out.c>

Reads global symbols (types T/D/B/R/A, defined-only) via nm, sorts by name,
and emits a const Ksym table into section .ksymtab.  link.ld places
.ksymtab as the LAST section, so addresses in the final kernel match the
first pass and the table itself is the only thing that grows.
(Also collects linker-script ABS symbols ('A', e.g. _lcd_fb_start/__ksymtab_*
when referenced) so .kdrv driver modules can resolve them.)
"""

import subprocess
import sys


def main():
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        sys.exit(2)
    elf, out = sys.argv[1], sys.argv[2]

    try:
        nm = subprocess.run(
            ["nm", "--defined-only", elf],
            capture_output=True, text=True, check=True,
        ).stdout
    except subprocess.CalledProcessError as e:
        sys.stderr.write("nm failed: %s\n" % e)
        sys.exit(1)

    syms = []
    for line in nm.splitlines():
        parts = line.split(None, 2)
        if len(parts) < 3:
            continue
        addr, typ, name = parts
        if typ not in "TDBRA":
            continue
        syms.append((name, addr))

    syms.sort(key=lambda s: s[0])

    with open(out, "w") as f:
        f.write("/* generated by gen_kernel_symtab.py - do not edit */\n")
        f.write('#include <plugin.h>\n\n')
        f.write('__attribute__((section(".ksymtab"), used))\n')
        f.write("const Ksym kernel_symtab[] = {\n")
        for name, addr in syms:
            f.write('    { "%s", (void *)0x%s },\n' % (name, addr))
        f.write("};\n\n")
        f.write('__attribute__((section(".ksymtab"), used))\n')
        f.write("const uint32_t kernel_symtab_count = %d;\n" % len(syms))
        sys.stderr.write("kernel_symtab: %d symbols\n" % len(syms))


if __name__ == "__main__":
    main()
