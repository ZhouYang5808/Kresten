#!/usr/bin/env python3
"""Pack dist/plugins/*.kplg and dist/drivers/*.kdrv into a C embed table
(kplg_embed.c).

Usage: pack_kplg_embed.py [--section NAME] <dir> [<dir> ...] <out.c>

Every .kplg/.kdrv becomes a static const byte array; the generated table
`kplg_embed_table[]` (with `kplg_embed_count`) lets plugin.c load modules
from memory when no ISO is available (ARM/RISC-V, and the x86 installer
kernel).  Table order is irrelevant - the load order is fixed by
plugin.c's kplg_auto[] and kdrv_auto[] lists.

--section: place the arrays in a named section (ARM/RISC-V use
.lx_img, which sits at a fixed high RAM address left free by the
old embedded busybox; keeps the ~2MB table out of .rodata so the
kernel's text stays small).
"""

import os
import sys


def main():
    args = sys.argv[1:]
    section = None
    if args and args[0] == "--section":
        section = args[1]
        args = args[2:]
    if len(args) < 2:
        sys.stderr.write(__doc__)
        sys.exit(2)
    dirs, out = args[:-1], args[-1]

    entries = []
    for d in dirs:
        for fn in sorted(os.listdir(d)):
            if not (fn.endswith(".kplg") or fn.endswith(".kdrv")):
                continue
            with open(os.path.join(d, fn), "rb") as f:
                data = f.read()
            entries.append((fn[:-5], data))

    with open(out, "w") as f:
        f.write("/* generated by pack_kplg_embed.py - do not edit */\n")
        f.write('#include <stdint.h>\n')
        f.write('#include "kplg_embed.h"\n\n')
        for name, data in entries:
            f.write("static const uint8_t _kplg_%s[] %s= {\n" % (
                name, '__attribute__((section(".lx_img"))) ' if section == ".lx_img" else ""))
            for i in range(0, len(data), 16):
                f.write("    " + ", ".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
            f.write("};\n\n")
        f.write("const KplgEmbed kplg_embed_table[] = {\n")
        for name, data in entries:
            f.write('    { "%s", _kplg_%s, sizeof(_kplg_%s) },\n' % (name, name, name))
        f.write("};\n\n")
        f.write("const uint32_t kplg_embed_count = %d;\n" % len(entries))
        sys.stderr.write("kplg_embed: %d modules, %d bytes total\n"
                         % (len(entries), sum(len(d) for _, d in entries)))


if __name__ == "__main__":
    main()
